/**
 * Generates content/read-aloud/chinese-rhymes.ts — the 蒙学顺口溜 shelf:
 * rhythmic recitation classics kids chant along to (三字经, 百家姓, 千字文,
 * 声律启蒙), chunked into lap-size pieces. Source: the public-domain 蒙学
 * texts in the chinese-poetry corpus, converted to simplified characters,
 * with machine-generated pinyin (pinyin-pro). Same pipeline rules as
 * gen-read-aloud-zh.mjs: never hand-edit the output; regenerate instead.
 * Run: node scripts/gen-read-aloud-rhymes.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { pinyin } from "pinyin-pro";
import * as OpenCC from "opencc-js";

const OUT = path.join(process.cwd(), "content/read-aloud/chinese-rhymes.ts");
const CACHE = path.join(process.cwd(), ".cache-read-aloud");
const BASE = "https://raw.githubusercontent.com/chinese-poetry/chinese-poetry/master/%E8%92%99%E5%AD%A6/";

const FORM = "蒙学顺口溜";
const NUMERALS = ["一", "二", "三", "四", "五", "六", "七", "八", "九", "十",
  "十一", "十二", "十三", "十四", "十五", "十六", "十七", "十八", "十九", "二十"];

fs.mkdirSync(CACHE, { recursive: true });
async function corpus(name) {
  const cacheFile = path.join(CACHE, `${name}.json`);
  if (!fs.existsSync(cacheFile)) {
    const res = await fetch(`${BASE}${name}.json`);
    if (!res.ok) throw new Error(`${name} fetch -> ${res.status}`);
    fs.writeFileSync(cacheFile, await res.text());
  }
  return JSON.parse(fs.readFileSync(cacheFile, "utf8"));
}

const toSimp = OpenCC.Converter({ from: "t", to: "cn" });

function splitLines(paragraph) {
  const clean = paragraph.replace(/[（(][^）)]*[）)]/g, "");
  return (clean.match(/[^，。；？！]+[，。；？！]?/g) ?? [])
    .map((s) => s.trim())
    .filter((s) => /[一-鿿]/.test(s));
}

function pinyinLine(hanzi) {
  return pinyin(hanzi)
    .replaceAll("，", ",")
    .replaceAll("。", ".")
    .replaceAll("；", ";")
    .replaceAll("？", "?")
    .replaceAll("！", "!")
    .replace(/\s+([,.;?!])/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

const pieces = [];
function addPiece({ slug, title, author, dynasty, lines }) {
  pieces.push({
    slug,
    title,
    pinyinTitle: pinyinLine(title),
    author,
    dynasty,
    form: FORM,
    lines: lines.map((hanzi) => ({ hanzi, pinyin: pinyinLine(hanzi) })),
  });
}

/** Chunk a flat hemistich list into numbered pieces of `size` lines. */
function chunked({ baseSlug, baseTitle, author, dynasty, hemistiches, size, take }) {
  for (let i = 0; i < take; i++) {
    const lines = hemistiches.slice(i * size, (i + 1) * size);
    if (lines.length < size / 2) break;
    addPiece({
      slug: `${baseSlug}-${i + 1}`,
      title: `${baseTitle} · 其${NUMERALS[i]}`,
      author,
      dynasty,
      lines,
    });
  }
}

// 三字经 — the ur-顺口溜: three-character couplets every kid chants.
{
  const d = await corpus("sanzijing-new");
  const hemistiches = d.paragraphs.flatMap((p) => splitLines(toSimp(p)));
  chunked({
    baseSlug: "san-zi-jing",
    baseTitle: "三字经",
    author: "王应麟（传）",
    dynasty: "宋",
    hemistiches,
    size: 16,
    take: 8,
  });
}

// 百家姓 — the surname chant (赵钱孙李…), pure rhythm.
{
  const d = await corpus("baijiaxing");
  const hemistiches = d.paragraphs.flatMap((p) => splitLines(toSimp(p)));
  chunked({
    baseSlug: "bai-jia-xing",
    baseTitle: "百家姓",
    author: "佚名",
    dynasty: "北宋",
    hemistiches,
    size: 16,
    take: 2,
  });
}

// 千字文 — four-character rhymed lines, no repeated character.
{
  const d = await corpus("qianziwen");
  const hemistiches = d.paragraphs.flatMap((p) => splitLines(toSimp(p)));
  chunked({
    baseSlug: "qian-zi-wen",
    baseTitle: "千字文",
    author: "周兴嗣",
    dynasty: "南朝·梁",
    hemistiches,
    size: 16,
    take: 6,
  });
}

// 声律启蒙 — the most musical of the four (云对雨，雪对风…); each rhyme
// section has three stanzas, and one stanza is one lap-size piece.
{
  const d = await corpus("shenglvqimeng");
  const upper = d.content[0]; // 上卷
  const RHYMES_TO_TAKE = 4;
  for (const chapter of upper.content.slice(0, RHYMES_TO_TAKE)) {
    const rhymeName = toSimp(chapter.chapter).replace(/\s+/g, "");
    for (const [i, stanza] of chapter.paragraphs.entries()) {
      addPiece({
        slug: `sheng-lv-qi-meng-${rhymeName ? pinyin(rhymeName, { toneType: "none" }).replace(/\s+/g, "-") : "x"}-${i + 1}`,
        title: `声律启蒙 · ${rhymeName} 其${NUMERALS[i]}`,
        author: "车万育",
        dynasty: "清",
        lines: splitLines(toSimp(stanza)),
      });
    }
  }
}

