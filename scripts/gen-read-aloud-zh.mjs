/**
 * Generates content/read-aloud/chinese-gen.ts from the public-domain
 * 唐诗三百首 corpus (chinese-poetry project), converted to simplified
 * characters, with machine-generated full-line pinyin (pinyin-pro, which
 * applies 不/一 tone sandhi). The 24 hand-curated poems in chinese.ts stay
 * authoritative; this file fills the collection to TARGET_TOTAL for the
 * grandparents' reading rotation. Run: node scripts/gen-read-aloud-zh.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { pinyin } from "pinyin-pro";
import * as OpenCC from "opencc-js";

const TARGET_TOTAL = 200;
const OUT = path.join(process.cwd(), "content/read-aloud/chinese-gen.ts");
const CACHE = path.join(process.cwd(), ".cache-read-aloud");
const URL =
  "https://raw.githubusercontent.com/chinese-poetry/chinese-poetry/master/%E8%92%99%E5%AD%A6/tangshisanbaishou.json";

// Regulated forms only — the long 古诗/乐府 pieces are not lap-reading material.
const FORMS = ["五言絕句", "七言絕句", "五言律詩", "七言律詩"];

fs.mkdirSync(CACHE, { recursive: true });
const cacheFile = path.join(CACHE, "tang300.json");
if (!fs.existsSync(cacheFile)) {
  const res = await fetch(URL);
  if (!res.ok) throw new Error(`corpus fetch -> ${res.status}`);
  fs.writeFileSync(cacheFile, await res.text());
}
const corpus = JSON.parse(fs.readFileSync(cacheFile, "utf8"));

const toSimp = OpenCC.Converter({ from: "t", to: "cn" });

/** Split a couplet paragraph into hemistiches, punctuation attached. */
function splitLines(paragraph) {
  const clean = paragraph.replace(/[（(][^）)]*[）)]/g, ""); // editorial notes
  return (clean.match(/[^，。；？！]+[，。；？！]?/g) ?? [])
    .map((s) => s.trim())
    .filter((s) => /[一-鿿]/.test(s));
}

function pinyinLine(hanzi) {
  return pinyin(hanzi)
    .replaceAll("，", ",")
    .replaceAll("。", ".")
    .replaceAll("；", ";")
    .replaceAll("？", "?")
    .replaceAll("！", "!")
    .replace(/\s+([,.;?!])/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

function slugify(title) {
  const base = pinyin(title, { toneType: "none" })
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, "")
    .trim()
    .replace(/\s+/g, "-");
  return base || "poem";
}

// Never duplicate a hand-curated poem: match on title or on first line.
const handwritten = fs.readFileSync(path.join(process.cwd(), "content/read-aloud/chinese.ts"), "utf8");
const strip = (s) => s.replace(/[，。；？！·（）\s]/g, "");
const isCurated = (title, firstLine) =>
  handwritten.includes(`"${title}`) || handwritten.includes(strip(firstLine).slice(0, 5));

const poems = [];
const seenSlugs = new Set();
const seenTitles = new Set();
for (const form of FORMS) {
  const section = corpus.content.find((s) => s.type === form);
  const formSimp = toSimp(form);
  for (const p of section.content) {
    if (poems.length >= TARGET_TOTAL - 24) break;
    const title = toSimp(p.chapter ?? "").trim();
    const author = toSimp(p.author ?? "").trim();
    if (!title || !author || !p.paragraphs?.length) continue;
    const lines = p.paragraphs.flatMap((par) => splitLines(toSimp(par)));
    if (lines.length < 2) continue;
    const titleKey = `${title}|${author}`;
    if (seenTitles.has(titleKey) || isCurated(title, lines[0])) continue;
    seenTitles.add(titleKey);
    let slug = slugify(title);
    for (let n = 2; seenSlugs.has(slug); n++) slug = `${slugify(title)}-${n}`;
    seenSlugs.add(slug);
    poems.push({
      slug,
      title,
      pinyinTitle: pinyinLine(title),
      author,
      dynasty: "唐",
      form: formSimp,
      lines: lines.map((hanzi) => ({ hanzi, pinyin: pinyinLine(hanzi) })),
    });
  }
}

const header = `import type { ChinesePoem } from "@/content-schema/read-aloud";

/**
 * GENERATED by scripts/gen-read-aloud-zh.mjs — do not hand-edit; regenerate
 * instead. Source: 唐诗三百首 (chinese-poetry corpus, public domain),
 * converted to simplified characters. Pinyin is machine-generated
 * (pinyin-pro): rare heteronyms may need a fix — fix them in the curated
 * chinese.ts by moving the poem there, not here.
 */
export const chinesePoemsGenerated: ChinesePoem[] = `;

fs.writeFileSync(OUT, header + JSON.stringify(poems, null, 2) + ";\n");
console.log(`wrote ${poems.length} poems to ${OUT}`);
for (const f of FORMS) console.log(toSimp(f), poems.filter((p) => p.form === toSimp(f)).length);
